ALTER PROCEDURE STPGETCLIENTEANIVER (
    TIPO Integer,
    DIAINI Integer,
    DIAFIM Integer,
    MES Integer,
    ANO Integer,
    DATA1 Date,
    DATA2 Date )
RETURNS (
    NOME Varchar(50),
    DATANASC Date,
    ENDERECO Varchar(50),
    CIDADE Varchar(50),
    BAIRRO Varchar(50),
    CEP Varchar(20),
    FONE Varchar(20) )
AS
BEGIN
   if (:TIPO = 0) then -- por dia mes e ano
   begin
     for select
           wec.NOME,
           wec.DATA,
           wec.ENDERECO,
           wec.CIDADE,
           wec.BAIRRO,
           wec.CEP,
           cli.TELEFONE
         from VIEWENDERECOCLIENTES wec
         left join CLIENTES cli on (wec.Codigo = cli.Codcliente)
        where (extract(month from DATA) = :MES)
          and (extract(day from DATA) between :DIAINI and :DIAFIM)
          and ((:ANO = -1) or (:ANO IS NULL))
         into :NOME,
              :DATANASC,
              :ENDERECO,
              :CIDADE,
              :BAIRRO,
              :CEP,
              :FONE
     do
       suspend;
   end
   else if (:TIPO = 1) then --entre datas
   begin
     for select
           wec.NOME,
           wec.DATA,
           wec.ENDERECO,
           wec.CIDADE,
           wec.BAIRRO,
           wec.CEP,
           cli.TELEFONE
         from VIEWENDERECOCLIENTES wec
        inner join CLIENTES cli on (wec.Codigo = cli.Codcliente)
        where (DATA between :DATA1 and :DATA2)
         into :NOME,
              :DATANASC,
              :ENDERECO,
              :CIDADE,
              :BAIRRO,
              :CEP,
              :FONE
     do
       suspend;
   end
end^
