CREATE VIEW VIEWRELCAIXACAIXAS (JAN, FEV, MAR, ABR, MAI, JUN, JUL, AGO, SEP, OUT, NOV, DEZ, NOME, SOMA)
AS 
  SELECT
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 1 THEN CX.VALOR ELSE 0 END) JAN,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 2 THEN CX.VALOR ELSE 0 END) FEV,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 3 THEN CX.VALOR ELSE 0 END) MAR,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 4 THEN CX.VALOR ELSE 0 END) ABR,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 5 THEN CX.VALOR ELSE 0 END) MAI,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 6 THEN CX.VALOR ELSE 0 END) JUN,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 7 THEN CX.VALOR ELSE 0 END) JUL,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 8 THEN CX.VALOR ELSE 0 END) AGO,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 9 THEN CX.VALOR ELSE 0 END) SEP,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 10 THEN CX.VALOR ELSE 0 END) OUT,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 11 THEN CX.VALOR ELSE 0 END) NOV,
      SUM(CASE WHEN EXTRACT(MONTH FROM CX.DATA) = 12 THEN CX.VALOR ELSE 0 END) DEZ,
      SUM(CX.VALOR) SOMA,
      CXS.NOME
  FROM CAIXA CX
  LEFT JOIN CAIXAS CXS ON (CX.CODCAIXAS = CXS.CODIGO)
  GROUP BY CXS.NOME
;
